// GetFamilyByID returns a family by its ID.
func GetFamilyByID(id string) *AircraftFamily {
	for _, f := range AircraftData.Families {
		if f.ID == id {
			return &f
		}
	}
	return nil
}

// GetTypeByID returns a type by its ID.
func GetTypeByID(id string) *AircraftType {
	for _, t := range AircraftData.Types {
		if t.ID == id {
			return &t
		}
	}
	return nil
}